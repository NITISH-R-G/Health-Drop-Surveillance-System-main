const fs = require('fs');
const path = require('path');

function updateReadme() {
  console.log('Generating Self-Updating README...');

  const readmePath = path.join(process.cwd(), 'README.md');
  const autoDir = path.join(process.cwd(), '.automation');

  let readmeContent = '';
  if (fs.existsSync(readmePath)) {
    readmeContent = fs.readFileSync(readmePath, 'utf8');
  }

  let analysis = { techStack: {} };
  if (fs.existsSync(path.join(autoDir, 'analysis.json'))) {
    analysis = JSON.parse(fs.readFileSync(path.join(autoDir, 'analysis.json'), 'utf8'));
  }

  let aiSummary = '';
  if (fs.existsSync(path.join(autoDir, 'ai-summary.md'))) {
    aiSummary = fs.readFileSync(path.join(autoDir, 'ai-summary.md'), 'utf8');
  }

  let mermaidDiagram = '';
  if (fs.existsSync(path.join(autoDir, 'architecture.mermaid'))) {
    mermaidDiagram = fs.readFileSync(path.join(autoDir, 'architecture.mermaid'), 'utf8');
  }

  const generatedSection = `
<!-- AUTOGENERATED_SECTION_START -->
## 🤖 Auto-Generated Repository Architecture

*This section is automatically generated and updated by the AI Documentation Agent.*

### 🧠 Architecture Summary
${aiSummary}

### 📊 Tech Stack Analysis
- **Frameworks**: ${analysis.techStack?.frameworks?.join(', ') || 'N/A'}
- **Libraries**: ${analysis.techStack?.libraries?.join(', ') || 'N/A'}
- **Tools**: ${analysis.techStack?.tools?.join(', ') || 'N/A'}

### 🗺️ Module Dependency Map
Below is an auto-generated dependency diagram showing the high-level architecture:

${mermaidDiagram}

[🔍 View Detailed SVG Interactive Dependency Graph](./.automation/dependency-graph.svg)

*Last updated: ${new Date().toUTCString()}*
<!-- AUTOGENERATED_SECTION_END -->
`;

  const sectionRegex =
    /<!-- AUTOGENERATED_SECTION_START -->[\s\S]*<!-- AUTOGENERATED_SECTION_END -->/;

  if (sectionRegex.test(readmeContent)) {
    // Replace existing section
    readmeContent = readmeContent.replace(sectionRegex, generatedSection.trim());
  } else {
    // Append to end of file if not present
    readmeContent += '\n' + generatedSection.trim() + '\n';
  }

  fs.writeFileSync(readmePath, readmeContent);
  console.log('README.md updated successfully.');
}

updateReadme();
